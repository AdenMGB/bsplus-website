/**
 * Wrangler local dev reads `.dev.vars`. Merge .env / .env.local and ensure DEV_* URLs exist.
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const devVarsPath = path.join(root, '.dev.vars')

function parseEnvFile(filePath) {
  const out = {}
  if (!fs.existsSync(filePath)) return out
  for (const line of fs.readFileSync(filePath, 'utf8').split('\n')) {
    const trimmed = line.trim()
    if (!trimmed || trimmed.startsWith('#')) continue
    const eq = trimmed.indexOf('=')
    if (eq === -1) continue
    const key = trimmed.slice(0, eq).trim()
    let value = trimmed.slice(eq + 1).trim()
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1)
    }
    out[key] = value
  }
  return out
}

function main() {
  const merged = {
    ...parseEnvFile(path.join(root, 'env.example')),
    ...parseEnvFile(path.join(root, '.env')),
    ...parseEnvFile(path.join(root, '.env.local')),
    ...parseEnvFile(devVarsPath),
  }

  merged.CF_DEV = merged.CF_DEV?.trim() || '1'
  merged.DEV_BSPLUS_URL = (merged.DEV_BSPLUS_URL?.trim() || 'http://localhost:8787').replace(/\/$/, '')
  merged.DEV_ACCOUNTS_URL = (merged.DEV_ACCOUNTS_URL?.trim() || 'http://localhost:8788').replace(/\/$/, '')
  merged.DEV_MAIL_URL = (merged.DEV_MAIL_URL?.trim() || 'http://localhost:8789').replace(/\/$/, '')

  const keys = [
    'CF_DEV',
    'DEV_BSPLUS_URL',
    'DEV_ACCOUNTS_URL',
    'DEV_MAIL_URL',
    'NUXT_OAUTH_CLIENT_ID',
    'NUXT_OAUTH_CLIENT_SECRET',
    'NUXT_OAUTH_REDIRECT_URI',
    'ACCOUNTS_API_KEY',
    'BS_MAIL_API_KEY',
    'BS_MAIL_FROM',
    'BS_MAIL_API_URL',
    'ACCOUNTS_API_URL',
    'NUXT_PUBLIC_SITE_URL',
    'FEEDBACK_IP_SALT',
  ]

  const lines = ['# Local worker secrets (auto-generated by scripts/sync-dev-vars.mjs)']
  for (const key of keys) {
    if (merged[key]?.trim()) lines.push(`${key}=${merged[key]}`)
  }
  for (const [key, value] of Object.entries(merged)) {
    if (keys.includes(key)) continue
    if (value?.trim()) lines.push(`${key}=${value}`)
  }

  fs.writeFileSync(devVarsPath, `${lines.join('\n')}\n`)
  console.log(`[sync-dev-vars] Wrote ${devVarsPath}`)
}

main()
